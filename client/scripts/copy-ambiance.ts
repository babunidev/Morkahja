/**
 * Copies the flat ambiance drop folder into client/public/UI/Ambiance,
 * one folder per expansion and stage, and brings each game copy to -38 LUFS.
 * The drop folder itself is left unchanged.
 */
import { spawn } from 'node:child_process';
import { copyFileSync, mkdirSync, readdirSync, renameSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { gameClipPath, placeDropFiles, type DropPlacement } from '../src/ui/music/ambianceDrop.js';

const TARGET_LUFS = -38;
const TOLERANCE_LU = 1;
const DROP_FOLDER = '/home/babuni/Projects/Assets/Morkahja/SFX/ambient';
const clientDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicRoot = path.join(clientDir, 'public');
const catalogPath = path.join(clientDir, 'src/ui/music/ambianceCatalog.ts');

function runFfmpeg(args: string[]): Promise<string> {
  return new Promise((resolve, reject) => {
    const child = spawn('ffmpeg', args, { stdio: ['ignore', 'ignore', 'pipe'] });
    let stderr = '';
    child.stderr.on('data', (chunk: Buffer) => {
      stderr += chunk.toString();
    });
    child.on('error', reject);
    child.on('close', (code) => {
      if (code === 0) {
        resolve(stderr);
        return;
      }
      reject(new Error(stderr.slice(-500)));
    });
  });
}

async function measure(filePath: string): Promise<{ lufs: number; peak: number }> {
  const stderr = await runFfmpeg(['-nostats', '-i', filePath, '-af', 'ebur128=peak=true', '-f', 'null', '-']);
  const summary = stderr.split('Summary:').pop() ?? '';
  const lufs = summary.match(/I:\s+(-?\d+(?:\.\d+)?)\s+LUFS/);
  const peak = summary.match(/Peak:\s+(-?\d+(?:\.\d+)?)\s+dBFS/);
  if (!lufs || !peak) {
    throw new Error(`Could not measure ${filePath}`);
  }
  return { lufs: Number(lufs[1]), peak: Number(peak[1]) };
}

async function encode(source: string, destination: string, gainDb: number): Promise<void> {
  const temporary = `${destination}.part.mp3`;
  await runFfmpeg([
    '-y',
    '-i',
    source,
    '-af',
    `volume=${gainDb.toFixed(2)}dB`,
    '-ar',
    '48000',
    '-ac',
    '2',
    '-c:a',
    'libmp3lame',
    '-b:a',
    '192k',
    temporary,
  ]);
  renameSync(temporary, destination);
}

async function writeLeveled(source: string, destination: string): Promise<{ lufs: number; peak: number }> {
  const measured = await measure(source);
  const gain = TARGET_LUFS - measured.lufs;
  if (Math.abs(gain) <= TOLERANCE_LU) {
    copyFileSync(source, destination);
    return measured;
  }

  const limitedGain = measured.peak + gain > -1 ? -1 - measured.peak : gain;
  await encode(source, destination, limitedGain);
  let after = await measure(destination);
  if (Math.abs(after.lufs - TARGET_LUFS) > TOLERANCE_LU) {
    const correction = TARGET_LUFS - after.lufs;
    const corrected = after.peak + correction > -1 ? -1 - after.peak : correction;
    await encode(destination, destination, corrected);
    after = await measure(destination);
  }
  return after;
}

function writeCatalog(placements: DropPlacement[]): void {
  const rows = placements
    .slice()
    .sort((a, b) => a.expansion - b.expansion || a.stage.localeCompare(b.stage) || a.number - b.number)
    .map((placement) => `  { expansion: ${placement.expansion}, stage: '${placement.stage}', url: assetUrl('${gameClipPath(placement)}') },`);
  const source = `import { assetUrl } from '../../assetUrl.js';
import type { AmbianceClip } from './ambianceLibrary.js';

/** Generated by client/scripts/copy-ambiance.ts. Do not edit by hand. */
export const AMBIANCE_CLIPS: readonly AmbianceClip[] = [
${rows.join('\n')}
];
`;
  writeFileSync(catalogPath, source);
}

async function mapPool<T, R>(items: T[], limit: number, worker: (item: T) => Promise<R>): Promise<R[]> {
  const results = new Array<R>(items.length);
  let next = 0;
  async function run(): Promise<void> {
    while (next < items.length) {
      const index = next;
      next += 1;
      results[index] = await worker(items[index]!);
    }
  }
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, () => run()));
  return results;
}

const names = readdirSync(DROP_FOLDER).filter((name) => name.endsWith('.mp3'));
const { placed, unknown } = placeDropFiles(names);
if (unknown.length > 0) {
  throw new Error(`Unrecognised ambiance names: ${unknown.join(', ')}`);
}

const results = await mapPool(placed, 6, async (placement) => {
  const destination = path.join(publicRoot, gameClipPath(placement).slice(1));
  mkdirSync(path.dirname(destination), { recursive: true });
  const after = await writeLeveled(path.join(DROP_FOLDER, placement.sourceName), destination);
  return { placement, ...after };
});

writeCatalog(placed);

const loudness = results.map((result) => result.lufs);
const quietest = results.reduce((best, result) => (result.lufs < best.lufs ? result : best));
const loudest = results.reduce((best, result) => (result.lufs > best.lufs ? result : best));
const outside = results.filter((result) => Math.abs(result.lufs - TARGET_LUFS) > TOLERANCE_LU);
console.log(`copied ${results.length} clips`);
console.log(`loudness ${Math.min(...loudness).toFixed(1)} to ${Math.max(...loudness).toFixed(1)} LUFS`);
console.log(`quietest ${quietest.placement.sourceName} ${quietest.lufs.toFixed(1)}`);
console.log(`loudest ${loudest.placement.sourceName} ${loudest.lufs.toFixed(1)}`);
console.log(`outside 1 LU: ${outside.length}`);
if (outside.length > 0) {
  process.exitCode = 1;
}
